export function normalizeLang(raw) {
  const code = String(raw || '').toLowerCase().slice(0, 2);
  if (code === 'ru' || code === 'be' || code === 'kk' || code === 'uk') return 'ru';
  if (code === 'tr') return 'tr';
  if (code === 'en') return 'en';
  return 'en';
}

export class I18n {
  constructor(initialLang = 'en') {
    this.lang = normalizeLang(initialLang);
  }

  setLang(lang) {
    this.lang = normalizeLang(lang);
    document.documentElement.lang = this.lang;
    document.title = this.t('pageTitle');
  }

  nextLang() {
    const idx = SUPPORTED_LANGS.indexOf(this.lang);
    const next = SUPPORTED_LANGS[(idx + 1) % SUPPORTED_LANGS.length];
    this.setLang(next);
    return next;
  }

  t(key, params = null) {
    const table = DICT[this.lang] || DICT.en;
    let text = table[key] ?? DICT.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  }
}
